// Measures each cut-out portrait so the team panels can show every head at the same
// height and size. Usage: pnpm framing (re-run when a cut-out in public/team/cutout changes).
// Output: src/content/framing.ts — per slug, the image size and the head's top, centre and
// width in source pixels, found from the alpha channel. Hair volume varies, so the team
// section can still nudge a member by hand (TUNE in TeamSection.tsx).
import { readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import sharp from "sharp";

const DIR = "public/team/cutout";
const OUT = "src/content/framing.ts";
const ALPHA = 128;

async function measure(file) {
  const { data, info } = await sharp(join(DIR, file))
    .ensureAlpha()
    .extractChannel(3)
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const span = (y) => {
    let left = -1;
    let right = -1;
    for (let x = 0; x < w; x++) {
      if (data[y * w + x] >= ALPHA) {
        if (left < 0) left = x;
        right = x;
      }
    }
    return left < 0 ? null : { left, right, width: right - left + 1 };
  };

  let top = 0;
  while (top < h && !span(top)) top++;

  // The head is the widest run in the first fifth below the top of the hair
  // (below that come the neck and shoulders).
  let head = span(top);
  for (let y = top; y < Math.min(h, top + h * 0.2); y++) {
    const s = span(y);
    if (s && s.width > head.width) head = s;
  }
  return {
    width: w,
    height: h,
    headTop: top,
    headCenter: Math.round((head.left + head.right) / 2),
    headWidth: head.width,
  };
}

const files = (await readdir(DIR)).filter((f) => f.endsWith(".png")).sort();
const entries = [];
for (const file of files) {
  const m = await measure(file);
  entries.push(`  "${file.replace(/\.png$/, "")}": ${JSON.stringify(m)},`);
  console.log(file, m);
}
await writeFile(
  OUT,
  `/** Generated by scripts/portrait-framing.mjs (pnpm framing). Source pixels of each cut-out. */
export const portraitFraming: Record<
  string,
  { width: number; height: number; headTop: number; headCenter: number; headWidth: number }
> = {
${entries.join("\n")}
};
`,
);
